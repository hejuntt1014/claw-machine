import { chromium } from 'playwright-core';
const W = Number(process.env.W ?? 390), H = Number(process.env.H ?? 844), TOUCH = process.env.TOUCH !== '0', P = process.env.PREFIX ?? 'm';
const url = (process.argv[2] ?? 'http://localhost:8787/') + '?q=0&noauto';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 2, hasTouch: TOUCH, isMobile: TOUCH });
const page = await ctx.newPage(); const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); }); page.on('pageerror', (e) => errs.push(String(e)));
const shot = async (n, clip) => { await page.waitForTimeout(350); await page.screenshot({ path: `shots/hints/${P}-${n}.png`, clip }); console.log('shot', n); };
const box = async (sel, pad = 14) => { const b = await page.locator(sel).first().boundingBox(); return { x: Math.max(0, b.x - pad), y: Math.max(0, b.y - pad), width: Math.min(W, b.width + pad * 2), height: b.height + pad * 2 }; };
const topClip = { x: 0, y: 0, width: W, height: Math.min(H, 220) };
await page.goto(url); await page.waitForFunction(() => !document.getElementById('go').disabled, null, { timeout: 120000 });
await shot('01-start', { x: 0, y: H * 0.45, width: W, height: H * 0.55 });
await page.click('#go', { force: true }); await page.waitForTimeout(1600);
await shot('02-onboard', { x: 0, y: 0, width: W, height: H });
await page.click('#obNext'); await page.waitForTimeout(300); await page.click('#obNext'); await shot('03-onboard3', await box('#onboard .panel', 20));
await page.click('#obNext'); await page.waitForTimeout(500);
await shot('04-idle-deck', { x: 0, y: H - 260, width: W, height: 260 });
await page.click('#grab', { force: true }); await shot('05-toast-insertfirst', topClip);
await page.click('#insert', { force: true }); await page.waitForTimeout(150); await shot('06-toast-coin', topClip);
await shot('07-play-deck', { x: 0, y: H - 260, width: W, height: 260 });
await page.evaluate(() => window.__claw.toast('剩余 5 秒', 'warn', '快下爪！', 4)); await shot('08-toast-5s', topClip);
await page.evaluate(() => window.__claw.toast('抓住了！', 'ok', '稳住…送往出口', 4)); await shot('09-toast-grab', topClip);
await page.evaluate(() => window.__claw.toast('差一点！', 'miss', '就差一点点掉进出口', 4)); await shot('10-toast-miss', topClip);
await page.evaluate(() => window.__claw.doGrab()); await page.waitForTimeout(700); await shot('11-busy-deck', { x: 0, y: H - 260, width: W, height: 260 });
await page.waitForFunction(() => window.__claw.game.state === 'idle', null, { timeout: 240000 }); await page.waitForTimeout(400);
await shot('12-result', { x: 0, y: 0, width: W, height: H });
await page.evaluate(() => window.__claw.openModal('nocoin')); await shot('13-nocoin', { x: 0, y: 0, width: W, height: H });
await page.click('#later'); await page.waitForTimeout(300);
// real win: put a prize into the chute
await page.evaluate(() => { const c = window.__claw; const p = c.game.prizes.find((q) => !q.won); p.body.setTranslation({ x: -0.36, y: 0.35, z: 0.27 }, true); p.body.setLinvel({ x: 0, y: -0.5, z: 0 }, true); });
await page.waitForFunction(() => document.getElementById('win').classList.contains('show'), null, { timeout: 30000 }); await page.waitForTimeout(1200);
await shot('14-win', { x: 0, y: 0, width: W, height: H });
await shot('14b-win-card', await box('#win .wcard', 16));
await page.click('#winOk'); await page.waitForTimeout(500);
await page.click('#set'); await shot('15-settings', { x: Math.max(0, W - 300), y: 0, width: Math.min(W, 300), height: 300 });
await page.mouse.click(W / 2, H / 2); await page.waitForTimeout(300);
await page.click('#bag'); await shot('16-bag', { x: 0, y: 0, width: W, height: H });
await page.click('#closeBag'); await page.waitForTimeout(300);
if (!TOUCH) { await page.evaluate(() => { localStorage.removeItem('claw_keys'); document.body.classList.remove('keys-off'); }); await shot('17-desktop-full', { x: 0, y: 0, width: W, height: H }); }
console.log('errors:', JSON.stringify(errs));
await browser.close();
